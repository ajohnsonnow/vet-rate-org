/**
 * apply-smc-rates.mjs — turn fetch-rate-tables.mjs's output into
 * src/data/vaSmcRatesHistorical.js (S44).
 *
 * Deliberately narrow: only the CURRENT-year entry from rate-tables.json is
 * used (see the scope decision in fetch-rate-tables.mjs's header — KnowVA's
 * archived historical COLA articles were found to disagree with the app's
 * already-verified vaPayRatesHistorical.js by up to ~$1 on some cells; only
 * the current year has been cross-validated clean against both that
 * existing data and a live va.gov fetch). If rate-tables.json ever contains
 * more than one entry (e.g. someone reruns the fetcher with
 * RATE_TABLES_INCLUDE_HISTORICAL=1), this script picks the entry whose
 * derived app-year matches an EXISTING vaPayRatesHistorical.js year and
 * still requires it to cross-validate exactly — it will never silently
 * promote an unverified year.
 *
 * Cross-validation is not optional: this script recomputes spouse/child/
 * parent deltas from the parsed article and compares them against
 * vaPayRatesHistorical.js's existing entry for the same app year, cell by
 * cell. Any mismatch throws — this is the safety net that caught the
 * historical-years discrepancy in the first place, so it stays load-bearing
 * for the current year too, not just a one-time check.
 *
 * Usage: node scripts/legal-ingestion/fetch-rate-tables.mjs
 *        node scripts/legal-ingestion/apply-smc-rates.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const RATE_TABLES_JSON = path.join(__dirname, ".work", "rate-tables.json");
const OUT_PATH = path.join(REPO_ROOT, "src", "data", "vaSmcRatesHistorical.js");

const TOLERANCE = 0.005;

/** "12/01/2025" -> app rate year 2026 (rates effective Dec 1 carry into the
 * following year's rate table, matching vaPayRatesHistorical.js's own
 * convention). Non-December effective dates map to their own year. */
export function appYearFor(effectiveDateMDY) {
  const m = /^(\d{1,2})\/(\d{1,2})\/(\d{4})$/.exec(effectiveDateMDY);
  if (!m) return null;
  const [, month, , year] = m;
  return Number(month) === 12 ? Number(year) + 1 : Number(year);
}

/**
 * Recompute the app-schema deltas from a parsed rate-tables.json entry and
 * diff them against vaPayRatesHistorical.js's existing entry for the same
 * year. Returns an array of mismatch strings (empty = clean).
 */
export function crossValidate(parsed, existingYearData) {
  const mismatches = [];
  const cmp = (label, computed, existing) => {
    for (const [pct, val] of Object.entries(existing)) {
      // The 0%-disability row is trivially $0 and isn't published in VA's
      // own rate table at all — not a real discrepancy to flag.
      if (pct === "0" && val === 0 && computed[pct] === undefined) continue;
      const c = computed[pct];
      if (typeof c !== "number" || Math.abs(c - val) > TOLERANCE) {
        mismatches.push(`${label}[${pct}]: computed=${c} existing=${val}`);
      }
    }
  };
  cmp("solo", parsed.veteran || {}, existingYearData.solo);
  const spouseDelta = Object.fromEntries(
    Object.entries(parsed.spouse || {}).map(([p, v]) => [
      p,
      v - (parsed.veteran?.[p] ?? NaN),
    ]),
  );
  cmp("spouse", spouseDelta, existingYearData.spouse);
  cmp("childUnder18", parsed.childUnder18 || {}, existingYearData.childUnder18);
  cmp("childSchool", parsed.childSchool || {}, existingYearData.childSchool);
  const p1Delta = Object.fromEntries(
    Object.entries(parsed.parentOne || {}).map(([p, v]) => [
      p,
      v - (parsed.veteran?.[p] ?? NaN),
    ]),
  );
  cmp("parentOne", p1Delta, existingYearData.parentOne);
  const p2Delta = Object.fromEntries(
    Object.entries(parsed.parentTwo || {}).map(([p, v]) => [
      p,
      v - (parsed.veteran?.[p] ?? NaN),
    ]),
  );
  cmp("parentTwo", p2Delta, existingYearData.parentTwo);
  return mismatches;
}

function generateFileContent(appYear, parsed) {
  const codesLiteral = parsed.smc
    .map(
      (e) =>
        `    { code: ${e.code}, award: ${JSON.stringify(e.award)}, basicRate: ${e.basicRate}, hospitalRate: ${e.hospitalRate === null ? "null" : e.hospitalRate}, notes: ${JSON.stringify(e.notes)} },`,
    )
    .join("\n");

  return `/**
 * Historical VA Special Monthly Compensation (SMC) rates.
 *
 * Generated by scripts/legal-ingestion/apply-smc-rates.mjs from KnowVA's
 * published rate tables (S44) — see fetch-rate-tables.mjs's header for the
 * full scope decision on why only current-year data is included here.
 *
 * SMC codes are keyed by KnowVA's internal numeric code, not the award
 * label alone — the same award abbreviation (e.g. "M") legitimately appears
 * more than once with different rates, reflecting different qualifying
 * statutory bases (see the "notes" footnote letters). getHistoricalSmcRate
 * returns every matching entry for an award rather than picking one.
 *
 * Regenerate for a new COLA year:
 *   node scripts/legal-ingestion/fetch-rate-tables.mjs
 *   node scripts/legal-ingestion/apply-smc-rates.mjs
 */

export const VA_SMC_RATES_HISTORICAL = {
  ${appYear}: {
    effectiveDate: ${JSON.stringify(parsed.effectiveDate)},
    colaIncrease: ${parsed.colaPercent},
    publicLaw: ${JSON.stringify(parsed.publicLaw)},
    sourceArticle: ${JSON.stringify(parsed.articleName)},
    codes: [
${codesLiteral}
    ],
  },
};

/**
 * Look up SMC rate entries for a year and award label (e.g. "K", "L", "S").
 * Returns every matching entry, since VA's own table legitimately has
 * multiple entries sharing an award label under different statutory bases.
 * @param {number} year
 * @param {string} award
 * @returns {{year:number, award:string, effectiveDate:string|null, matches:Array<Object>}}
 */
export function getHistoricalSmcRate(year, award) {
  const yearData = VA_SMC_RATES_HISTORICAL[year];
  if (!yearData) {
    return { year, award, effectiveDate: null, matches: [] };
  }
  const needle = String(award).trim().toUpperCase();
  const matches = yearData.codes.filter(
    (c) => c.award.trim().toUpperCase() === needle,
  );
  return { year, award, effectiveDate: yearData.effectiveDate, matches };
}

export default VA_SMC_RATES_HISTORICAL;
`;
}

async function main() {
  const entries = JSON.parse(readFileSync(RATE_TABLES_JSON, "utf8"));
  if (entries.length === 0) {
    throw new Error(
      "rate-tables.json is empty — run fetch-rate-tables.mjs first",
    );
  }

  const { VA_PAY_RATES_HISTORICAL } = await import(
    pathToFileURL(
      path.join(REPO_ROOT, "src", "data", "vaPayRatesHistorical.js"),
    ).href
  );

  let applied = null;
  for (const parsed of entries) {
    const appYear = appYearFor(parsed.effectiveDate);
    const existing = VA_PAY_RATES_HISTORICAL[appYear];
    if (!existing) {
      console.warn(
        `[apply-smc-rates] "${parsed.articleName}" → app year ${appYear} has no existing vaPayRatesHistorical.js entry to cross-validate against — skipping (cannot verify)`,
      );
      continue;
    }
    const mismatches = crossValidate(parsed, existing);
    if (mismatches.length > 0) {
      console.warn(
        `[apply-smc-rates] "${parsed.articleName}" → app year ${appYear}: ${mismatches.length} cross-validation mismatches, refusing to use this year:`,
      );
      mismatches.slice(0, 10).forEach((m) => console.warn(`  ${m}`));
      continue;
    }
    console.log(
      `[apply-smc-rates] "${parsed.articleName}" → app year ${appYear}: cross-validated clean (${parsed.smc.length} SMC codes)`,
    );
    applied = { appYear, parsed };
    break; // current-year-only scope — first clean match wins
  }

  if (!applied) {
    throw new Error(
      "No rate-tables.json entry cross-validated cleanly against vaPayRatesHistorical.js — refusing to generate vaSmcRatesHistorical.js with unverified data",
    );
  }

  const content = generateFileContent(applied.appYear, applied.parsed);
  writeFileSync(OUT_PATH, content);
  console.log(
    `[apply-smc-rates] wrote src/data/vaSmcRatesHistorical.js (app year ${applied.appYear} only)`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(`[apply-smc-rates] FAILED: ${e.message}`);
    process.exit(1);
  });
}
